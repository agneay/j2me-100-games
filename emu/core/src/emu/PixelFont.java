    /** rows[glyph*GH + row] = 5-bit mask, bit 4 = leftmost column. */
    private static final int[] ROWS = new int[SRC.length * GH];

    static {
        for (int g = 0; g < SRC.length; g++) {
            String s = SRC[g];
            int row = 0, col = 0, bits = 0;
            for (int i = 0; i <= s.length(); i++) {
                char c = i < s.length() ? s.charAt(i) : '|';
                if (c == '|') {
                    ROWS[g * GH + row] = bits;
                    row++;
                    col = 0;
                    bits = 0;
                } else {
                    if (c == '#') bits |= 1 << (GW - 1 - col);
                    col++;
                }
            }
        }
    }

    private PixelFont() {}

    /** Returns the 5-bit row mask for a character. */
    public static int row(char ch, int row) {
        int g = ch - 32;
        if (g < 0 || g >= SRC.length) g = '?' - 32;
        return ROWS[g * GH + row];
    }
